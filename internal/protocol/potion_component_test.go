func TestDecodeSetCreativeModeSlotPotionComponentFixtures(t *testing.T) {
	fixtures := map[string]untrustedSlotFixture{
		"base potion only": {
			data: []byte{0x00, 0x24, 0x01, 0xE1, 0x08, 0x01, 0x00, 0x31, 0x05, 0x01, 0x0A, 0x00, 0x00, 0x00},
			item: game.ItemStack{
				Item:       game.ItemPotion,
				Count:      1,
				Components: []game.ItemComponent{{Type: game.ItemComponentPotionContents, Data: []byte{0x01, 0x0A, 0x00, 0x00, 0x00}}},
			},
		},
		"custom color": {
			data: []byte{0x00, 0x24, 0x01, 0xE1, 0x08, 0x01, 0x00, 0x31, 0x08, 0x00, 0x01, 0x12, 0x34, 0x56, 0x78, 0x00, 0x00},
			item: game.ItemStack{
				Item:       game.ItemPotion,
				Count:      1,
				Components: []game.ItemComponent{{Type: game.ItemComponentPotionContents, Data: []byte{0x00, 0x01, 0x12, 0x34, 0x56, 0x78, 0x00, 0x00}}},
			},
		},
		"custom name": {
			data: []byte{0x00, 0x24, 0x01, 0xE1, 0x08, 0x01, 0x00, 0x31, 0x09, 0x00, 0x00, 0x00, 0x01, 0x04, 'T', 'e', 's', 't'},
			item: game.ItemStack{
				Item:       game.ItemPotion,
				Count:      1,
				Components: []game.ItemComponent{{Type: game.ItemComponentPotionContents, Data: []byte{0x00, 0x00, 0x00, 0x01, 0x04, 'T', 'e', 's', 't'}}},
			},
		},
		"one custom effect": {
			data: []byte{0x00, 0x24, 0x01, 0xE1, 0x08, 0x01, 0x00, 0x31, 0x0C, 0x00, 0x00, 0x01, 0x01, 0x02, 0xAC, 0x02, 0x00, 0x01, 0x01, 0x00, 0x00},
			item: game.ItemStack{
				Item:       game.ItemPotion,
				Count:      1,
				Components: []game.ItemComponent{{Type: game.ItemComponentPotionContents, Data: []byte{0x00, 0x00, 0x01, 0x01, 0x02, 0xAC, 0x02, 0x00, 0x01, 0x01, 0x00, 0x00}}},
			},
		},
		"several custom effects": {
			data: []byte{0x00, 0x24, 0x01, 0xE1, 0x08, 0x01, 0x00, 0x31, 0x13, 0x00, 0x00, 0x02, 0x01, 0x00, 0x20, 0x01, 0x00, 0x01, 0x00, 0x02, 0x03, 0xAC, 0x02, 0x00, 0x01, 0x00, 0x00, 0x00},
			item: game.ItemStack{
				Item:       game.ItemPotion,
				Count:      1,
				Components: []game.ItemComponent{{Type: game.ItemComponentPotionContents, Data: []byte{0x00, 0x00, 0x02, 0x01, 0x00, 0x20, 0x01, 0x00, 0x01, 0x00, 0x02, 0x03, 0xAC, 0x02, 0x00, 0x01, 0x00, 0x00, 0x00}}},
			},
		},
		"hidden effect chain": {
			data: []byte{0x00, 0x24, 0x01, 0xE1, 0x08, 0x01, 0x00, 0x31, 0x11, 0x00, 0x00, 0x01, 0x01, 0x02, 0x64, 0x00, 0x01, 0x01, 0x01, 0x01, 0x14, 0x01, 0x00, 0x01, 0x00, 0x00},
			item: game.ItemStack{
				Item:       game.ItemPotion,
				Count:      1,
				Components: []game.ItemComponent{{Type: game.ItemComponentPotionContents, Data: []byte{0x00, 0x00, 0x01, 0x01, 0x02, 0x64, 0x00, 0x01, 0x01, 0x01, 0x01, 0x14, 0x01, 0x00, 0x01, 0x00, 0x00}}},
			},
		},
		"duration scale": {
			data: []byte{0x00, 0x24, 0x01, 0xE1, 0x08, 0x02, 0x00, 0x31, 0x05, 0x01, 0x0A, 0x00, 0x00, 0x00, 0x32, 0x04, 0x3F, 0x00, 0x00, 0x00},
			item: game.ItemStack{
				Item:  game.ItemPotion,
				Count: 1,
				Components: []game.ItemComponent{
					{Type: game.ItemComponentPotionContents, Data: []byte{0x01, 0x0A, 0x00, 0x00, 0x00}},
					{Type: game.ItemComponentPotionDurationScale, Data: []byte{0x3F, 0x00, 0x00, 0x00}},
				},
			},
		},
	}

	for name, fixture := range fixtures {
		t.Run(name, func(t *testing.T) {
			update, err := DecodeSetCreativeModeSlot(fixture.data)
			if err != nil {
				t.Fatalf("decode creative potion slot: %v", err)
			}

			if update.Slot != 36 || update.Item.ItemID != int32(fixture.item.Item) || update.Item.ItemCount != fixture.item.Count {
				t.Fatalf("creative potion slot = %+v", update)
			}

			componentsEqual := func(first, second game.ItemComponent) bool {
				return first.Type == second.Type && slices.Equal(first.Data, second.Data)
			}

			if !slices.EqualFunc(update.Item.Components, fixture.item.Components, componentsEqual) {
				t.Fatalf("creative potion components = %v, want %v", update.Item.Components, fixture.item.Components)
			}
		})
	}
}

func TestDecodeSetCreativeModeSlotRejectsMalformedPotionComponents(t *testing.T) {
	fixtures := map[string][]byte{
		"invalid potion holder":       {0x00, 0x24, 0x01, 0xE1, 0x08, 0x01, 0x00, 0x31, 0x02, 0x01, 0x7F},
		"invalid effect holder":       {0x00, 0x24, 0x01, 0xE1, 0x08, 0x01, 0x00, 0x31, 0x04, 0x00, 0x00, 0x01, 0x28},
		"malformed recursive details": {0x00, 0x24, 0x01, 0xE1, 0x08, 0x01, 0x00, 0x31, 0x0A, 0x00, 0x00, 0x01, 0x01, 0x00, 0x01, 0x00, 0x01, 0x01, 0x01},
		"oversized effect list":       {0x00, 0x24, 0x01, 0xE1, 0x08, 0x01, 0x00, 0x31, 0x04, 0x00, 0x00, 0x81, 0x02},
		"trailing component bytes":    {0x00, 0x24, 0x01, 0xE1, 0x08, 0x01, 0x00, 0x31, 0x06, 0x01, 0x0A, 0x00, 0x00, 0x00, 0xFF},
	}

	for name, data := range fixtures {
		t.Run(name, func(t *testing.T) {
			_, err := DecodeSetCreativeModeSlot(data)
			if err == nil {
				t.Fatal("malformed creative potion slot decoded")
			}
		})
	}
}
